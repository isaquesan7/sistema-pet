#!/bin/sh
# PointVet M.5.58 — restore operacional SOMENTE em PostgreSQL Railway isolado.
# Usa bancos fictícios criados nesta execução. Não lê staging/produção nem
# aceita host público; nunca remove um banco preexistente.
set -eu
umask 077

die() { printf 'POINTVET_DRILL_BLOCKED: %s\n' "$*" >&2; exit 1; }
test "${POINTVET_DRILL_SCOPE:-}" = 'isolated-synthetic-20261020' || die 'scope invalido'
test -n "${RAILWAY_PROJECT_ID:-}" || die 'ambiente Railway nao detectado'
test "${RAILWAY_PROJECT_ID:-}" = "${POINTVET_DRILL_PROJECT_ID:-}" || die 'project id divergente'
test -n "${PGHOST:-}" || die 'PGHOST ausente'
case "$PGHOST" in *.railway.internal) ;; *) die 'host fora da rede privada Railway' ;; esac
test -n "${PGUSER:-}" || die 'PGUSER ausente'
test -n "${PGPASSWORD:-}" || die 'PGPASSWORD ausente'
test -n "${PGDATABASE:-}" || die 'PGDATABASE ausente'
test -n "${PGPORT:-}" || die 'PGPORT ausente'
command -v pg_dump >/dev/null 2>&1 || die 'pg_dump ausente'
command -v pg_restore >/dev/null 2>&1 || die 'pg_restore ausente'
command -v sha256sum >/dev/null 2>&1 || die 'sha256sum ausente'

src='pointvet_synthetic_source'
dst='pointvet_synthetic_restore'
scratch=$(mktemp -d /tmp/pointvet-drill.XXXXXXXX)
trap 'rm -rf "$scratch"' EXIT HUP INT TERM

# Falhar fechado: o executor não pode sobrescrever bancos existentes.
identity=$(psql -X -At -v ON_ERROR_STOP=1 -d "$PGDATABASE" \
  -c "SELECT current_database() || ':' || current_user")
test -n "$identity" || die 'identidade de conexao vazia'
existing=$(psql -X -At -v ON_ERROR_STOP=1 -d "$PGDATABASE" \
  -c "SELECT count(*) FROM pg_database WHERE datname IN ('$src','$dst')")
test "$existing" = '0' || die 'banco de origem/destino ja existe; recusa sobrescrita'
printf 'POINTVET_DRILL_START: project=%s source=%s target=%s pg_version=' \
  "$RAILWAY_PROJECT_ID" "$src" "$dst"
psql -X -At -v ON_ERROR_STOP=1 -d "$PGDATABASE" -c 'SHOW server_version'

psql -X -q -v ON_ERROR_STOP=1 -d "$PGDATABASE" -c "CREATE DATABASE $src"
psql -X -q -v ON_ERROR_STOP=1 -d "$PGDATABASE" -c "CREATE DATABASE $dst"

# Fixture representativa, pequena e exclusivamente fictícia.
psql -X -q -v ON_ERROR_STOP=1 -d "$src" <<'SQL'
CREATE TABLE empresas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cnpj_ficticio text UNIQUE NOT NULL CHECK (length(cnpj_ficticio) = 14),
  nome text NOT NULL
);
CREATE TABLE produtos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  estoque_inicial_gramas integer NOT NULL CHECK (estoque_inicial_gramas >= 0)
);
CREATE TABLE vendas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES empresas(id),
  produto_id integer REFERENCES produtos(id),
  centavos integer NOT NULL CHECK (centavos > 0),
  gramas integer NOT NULL CHECK (gramas >= 0),
  status text NOT NULL CHECK (status IN ('FECHADA','ESTORNADA'))
);
CREATE TABLE estornos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id integer UNIQUE NOT NULL REFERENCES vendas(id),
  gramas_repostas integer NOT NULL CHECK (gramas_repostas >= 0),
  motivo text NOT NULL
);
CREATE INDEX idx_vendas_empresa ON vendas(empresa_id);
INSERT INTO empresas (cnpj_ficticio,nome) VALUES
  ('00000000000000','Empresa Sintetica A'),
  ('11111111111111','Empresa Sintetica B');
INSERT INTO produtos (nome,estoque_inicial_gramas) VALUES
  ('Racao ficticia a granel',1000);
INSERT INTO vendas (empresa_id,produto_id,centavos,gramas,status) VALUES
  (1,1,500,333,'ESTORNADA'),
  (2,NULL,1000,0,'FECHADA');
INSERT INTO estornos (venda_id,gramas_repostas,motivo) VALUES
  (1,333,'Ensaio inteiramente sintetico');
SQL

source_ready=$(psql -X -At -v ON_ERROR_STOP=1 -d "$src" -c "
SELECT CASE WHEN (SELECT count(*) FROM empresas)=2
 AND (SELECT count(*) FROM vendas)=2
 AND (SELECT sum(centavos) FROM vendas)=1500
 AND (SELECT sum(gramas) FROM vendas)=333
 AND (SELECT sum(gramas_repostas) FROM estornos)=333
 AND (SELECT sum(estoque_inicial_gramas) FROM produtos)=1000
 THEN 'READY' ELSE 'INVALID' END")
test "$source_ready" = 'READY' || die 'fixture sintetica invalida'

backup_start=$(date +%s)
pg_dump --format=custom --no-owner --no-acl -d "$src" -f "$scratch/pointvet.dump"
test -s "$scratch/pointvet.dump" || die 'dump vazio'
bytes=$(wc -c < "$scratch/pointvet.dump" | tr -d ' ')
test "$bytes" -gt 5000 || die 'dump pequeno demais'
sha256sum "$scratch/pointvet.dump" > "$scratch/pointvet.sha256"
backup_ready=$(date +%s)

restore_start=$(date +%s)
pg_restore --exit-on-error --no-owner --no-acl -d "$dst" "$scratch/pointvet.dump" \
  > "$scratch/restore.log" 2>&1 || die 'pg_restore falhou'
restore_ready=$(date +%s)
sha256sum -c "$scratch/pointvet.sha256" >/dev/null || die 'checksum do dump divergente'

# Fingerprint de dados e esquema após pg_dump/pg_restore, sem expor dados.
fingerprint() {
  psql -X -At -v ON_ERROR_STOP=1 -d "$1" -c "
SELECT md5(concat_ws('|',
 (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id)::text,'[]') FROM empresas t),
 (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id)::text,'[]') FROM produtos t),
 (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id)::text,'[]') FROM vendas t),
 (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id)::text,'[]') FROM estornos t),
 (SELECT md5(coalesce(string_agg(indexdef,';' ORDER BY indexname),''))
  FROM pg_indexes WHERE schemaname='public'),
 (SELECT count(*)::text FROM pg_constraint c
  JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname='public'),
 (SELECT md5(coalesce(string_agg(sequencename||':'||coalesce(last_value::text,'NULL'),
  ';' ORDER BY sequencename),'')) FROM pg_sequences WHERE schemaname='public')
))"
}
src_fp=$(fingerprint "$src")
dst_fp=$(fingerprint "$dst")
test -n "$src_fp" || die 'fingerprint origem vazio'
test "$src_fp" = "$dst_fp" || die 'divergencia de dados/esquema/indices/sequencias'

# Verificar integridade operacional dos gramas e duas empresas depois do restore.
business=$(psql -X -At -v ON_ERROR_STOP=1 -d "$dst" -c "
SELECT CASE WHEN
 (SELECT count(DISTINCT empresa_id) FROM vendas)=2 AND
 (SELECT sum(gramas) FROM vendas WHERE status='ESTORNADA')=
 (SELECT sum(gramas_repostas) FROM estornos) AND
 (SELECT sum(estoque_inicial_gramas) FROM produtos)
 - (SELECT sum(gramas) FROM vendas)=667 AND
 (SELECT sum(estoque_inicial_gramas) FROM produtos)
 - (SELECT sum(gramas) FROM vendas)
 + (SELECT sum(gramas_repostas) FROM estornos)=1000
 THEN 'READY' ELSE 'DIVERGENT' END")
test "$business" = 'READY' || die 'empresas, estorno ou gramas inconsistentes'

printf 'POINTVET_DRILL_SUCCESS: dump_bytes=%s backup_seconds=%s restore_seconds=%s table_count=4 company_count=2 sales=2 refunds=1 grams_refunded=333 sha256=%s\n' \
  "$bytes" "$((backup_ready - backup_start))" "$((restore_ready - restore_start))" \
  "$(cut -c1-16 "$scratch/pointvet.sha256")"
printf 'POINTVET_DRILL_SCOPE: PostgreSQL TEMPORARIO; sem acesso a bancos Pet King staging/producao\n'
# Manter o job online brevemente para coleta de logs; cleanup apaga recursos.
sleep 600
